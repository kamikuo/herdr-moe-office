"""A character's frames -> one sprite sheet per action, facing and layer.

Usage: pack_sheets.py <character>   (run by build_video.py at its end; or on its own)
Input : mods/moe-office/chars/<character>/<anim>_<i>[_l]{.png,_hair.svg,_shade.png}, char.js
Output: mods/moe-office/chars/<character>/<anim>[_l]{.png,_hair.svg,_shade.png}, and char.js
        with each action's `cols` and the sheet's `pad`. The single frames are deleted.

Why: a girl changing frames used to mean three new files to show; with many girls (all the
characters at once) a slower Mac couldn't keep them all ready, and a girl blinked out while
hers loaded. With sheets, a frame change only moves the sheet inside her box: every action
is three files, loaded once.

Frames sit in a grid, `cols` across, PAD px apart (transparent), so scaling the sheet never
bleeds a neighbour's edge into her box.
"""
import sys, os, re, json, glob, base64, io
from PIL import Image

NAME = sys.argv[1]
OUT = f"mods/moe-office/chars/{NAME}"
PAD = 4


def cols_for(n):
    """About square, so no sheet gets too wide for the GPU."""
    c = 1
    while c * c < n: c += 1
    return c


def hair_png(path):
    """The mask PNG inside a frame's _hair.svg."""
    with open(path) as f:
        data = re.search(r'base64,([^"]+)"', f.read()).group(1)
    return Image.open(io.BytesIO(base64.b64decode(data))).convert("LA")


def write_hair(sheet, path):
    buf = io.BytesIO()
    sheet.save(buf, "PNG", optimize=True)
    data = base64.b64encode(buf.getvalue()).decode()
    w, h = sheet.size
    with open(path, "w") as f:
        f.write(f'<svg xmlns="http://www.w3.org/2000/svg" xmlns:xlink="http://www.w3.org/1999/xlink" width="{w}" height="{h}" viewBox="0 0 {w} {h}">'
                f'<image width="{w}" height="{h}" xlink:href="data:image/png;base64,{data}"/></svg>')


def main():
    src = open(f"{OUT}/char.js").read()
    manifest = json.loads(src[src.index("{"):src.rindex("}") + 1])
    for name, a in manifest["anim"].items():
        n, w, h = a["n"], a["w"], a["h"]
        cols = cols_for(n)
        rows = (n + cols - 1) // cols
        size = (cols * (w + PAD), rows * (h + PAD))
        at = lambda i: ((i % cols) * (w + PAD), (i // cols) * (h + PAD))
        for suffix in ("", "_l"):
            frame = lambda i, ext: f"{OUT}/{name}_{i}{suffix}{ext}"
            base, shade = Image.new("RGBA", size, (0, 0, 0, 0)), Image.new("RGBA", size, (0, 0, 0, 0))
            hair = Image.new("LA", size, (255, 0))
            for i in range(n):
                base.paste(Image.open(frame(i, ".png")).convert("RGBA"), at(i))
                shade.paste(Image.open(frame(i, "_shade.png")).convert("RGBA"), at(i))
                hair.paste(hair_png(frame(i, "_hair.svg")), at(i))
            # As the frames were: 256 colours for her, 32 (black or white at 16 strengths) for
            # the shading, no dithering.
            base.quantize(256, method=Image.Quantize.FASTOCTREE, dither=Image.Dither.NONE).save(f"{OUT}/{name}{suffix}.png", optimize=True)
            shade.quantize(32, method=Image.Quantize.FASTOCTREE, dither=Image.Dither.NONE).save(f"{OUT}/{name}{suffix}_shade.png", optimize=True)
            write_hair(hair, f"{OUT}/{name}{suffix}_hair.svg")
        a["cols"] = cols
        print(f"{name}: {n} frames, {cols}x{rows}, {size[0]}x{size[1]}")
    manifest["pad"] = PAD
    for f in glob.glob(f"{OUT}/*_[0-9]*"):
        if re.search(r"_\d+(_l)?(\.png|_hair\.svg|_shade\.png)$", f): os.remove(f)
    with open(f"{OUT}/char.js", "w") as f:
        f.write("// Generated by tools/build_video.py (sheets: tools/pack_sheets.py)\nexport const CHAR = " + json.dumps(manifest, indent=1) + ";\n")


main()
